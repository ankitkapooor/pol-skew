"""Build U.S. benchmark norms from ANES 2024 and CES 2024 microdata.

Usage:
    python scripts/norms/build_norms.py                      # real data from data/raw → data/norms/us-2024.json
    python scripts/norms/build_norms.py --anes A.csv --ces C.csv --out X.json [--synthetic]

Reads item definitions from data/benchmark-items.json. Writes only aggregate tables with provenance.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from weighted import keyed_step, percentile_table, weighted_distribution  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
ITEMS_FILE = ROOT / "data" / "benchmark-items.json"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_hash() -> str:
    try:
        rev = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
        dirty = subprocess.call(["git", "diff", "--quiet"], cwd=ROOT) != 0
        return rev + ("-dirty" if dirty else "")
    except Exception:  # noqa: BLE001
        return "unknown"


def load(path: Path, columns: list[str]) -> pd.DataFrame:
    """Load only the needed columns (case-insensitive) from CSV, Stata or SPSS."""
    suffix = path.suffix.lower()
    if suffix == ".csv":
        header = pd.read_csv(path, nrows=0).columns
        lookup = {c.lower(): c for c in header}
        missing = [c for c in columns if c.lower() not in lookup]
        if missing:
            raise SystemExit(f"{path.name}: missing columns {missing}. Check the file version against data/SOURCES.md.")
        df = pd.read_csv(path, usecols=[lookup[c.lower()] for c in columns], low_memory=False)
    elif suffix in (".dta", ".sav"):
        import pyreadstat

        reader = pyreadstat.read_dta if suffix == ".dta" else pyreadstat.read_sav
        _, meta = reader(str(path), metadataonly=True)
        lookup = {c.lower(): c for c in meta.column_names}
        missing = [c for c in columns if c.lower() not in lookup]
        if missing:
            raise SystemExit(f"{path.name}: missing columns {missing}.")
        df, _ = reader(str(path), usecols=[lookup[c.lower()] for c in columns], apply_value_formats=False)
    else:
        raise SystemExit(f"Unsupported file type: {path}")
    # Normalise to the spelling in benchmark-items.json (usecols keeps file order, so map by name).
    df = df.rename(columns={lookup[c.lower()]: c for c in columns})[columns]
    return df.apply(pd.to_numeric, errors="coerce")


def recode(series: pd.Series, item: dict) -> pd.Series:
    """Keep offered codes (substantive + offered non-substantive); everything else → NA."""
    keep = {o["code"] for o in item["options"]} | {o["code"] for o in item["offeredNonSubstantive"]}
    return series.where(series.isin(keep))


def build(spec: dict, paths: dict[str, Path], synthetic: bool) -> dict:
    out: dict = {
        "$comment": "Generated by scripts/norms/build_norms.py. Aggregate tables only; no microdata.",
        "itemsVersion": spec["version"],
        "synthetic": synthetic,
        "builtOn": dt.datetime.now(dt.timezone.utc).date().isoformat(),
        "scriptGitHash": git_hash(),
        "sources": {},
        "items": {},
        "composites": {},
    }
    frames: dict[str, pd.DataFrame] = {}
    for key, src in spec["sources"].items():
        items = [i for i in spec["items"] if i["source"] == key]
        cols = [src["weight"], *[i["variable"] for i in items]]
        df = load(paths[key], cols)
        w = df[src["weight"]]
        df = df[w.notna() & (w > 0)].reset_index(drop=True)
        frames[key] = df
        out["sources"][key] = {
            "name": src["name"],
            "short": src["short"],
            "release": src["release"],
            "population": src["population"],
            "citation": src["citation"],
            "file": paths[key].name,
            "sha256": sha256(paths[key]),
            "weight": src["weight"],
            "unweightedN": int(len(df)),
            "weightedN": float(df[src["weight"]].sum()),
        }

    for item in spec["items"]:
        src = spec["sources"][item["source"]]
        df = frames[item["source"]]
        codes = [o["code"] for o in item["options"]] + [o["code"] for o in item["offeredNonSubstantive"]]
        d = weighted_distribution(recode(df[item["variable"]], item).tolist(), df[src["weight"]].tolist(), codes)
        out["items"][item["id"]] = {"source": item["source"], "variable": item["variable"], **d}

    by_id = {i["id"]: i for i in spec["items"]}
    for name, comp in spec["composites"].items():
        src = spec["sources"][comp["source"]]
        df = frames[comp["source"]]
        steps = pd.DataFrame(
            {
                iid: [keyed_step(by_id[iid], None if pd.isna(v) else int(v)) for v in df[by_id[iid]["variable"]]]
                for iid in comp["items"]
            }
        )
        complete = steps.notna().all(axis=1)
        total = steps[complete].sum(axis=1).astype(int)
        weights = df.loc[complete, src["weight"]]
        max_total = sum(6 for _ in comp["items"])
        t = percentile_table(total.tolist(), weights.tolist(), range(0, max_total + 1))
        out["composites"][name] = {"source": comp["source"], "items": comp["items"], "min": 0, "max": max_total, **t}
    return out


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--anes", type=Path)
    p.add_argument("--ces", type=Path)
    p.add_argument("--out", type=Path, default=ROOT / "data" / "norms" / "us-2024.json")
    p.add_argument("--synthetic", action="store_true", help="mark the output as synthetic (for fixtures)")
    a = p.parse_args(argv)
    spec = json.loads(ITEMS_FILE.read_text())
    paths = {
        "anes2024": a.anes or ROOT / spec["sources"]["anes2024"]["expectedFile"],
        "ces2024": a.ces or ROOT / spec["sources"]["ces2024"]["expectedFile"],
    }
    for k, path in paths.items():
        if not path.exists():
            raise SystemExit(f"Missing {k} file: {path}. See data/raw/README.md.")
    result = build(spec, paths, a.synthetic)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps(result, indent=1) + "\n")
    print(f"Wrote {a.out}")
    for k, s in result["sources"].items():
        print(f"  {k}: N={s['unweightedN']} (weighted {s['weightedN']:.0f}), weight {s['weight']}")


if __name__ == "__main__":
    main()
